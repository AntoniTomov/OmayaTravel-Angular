// Run: node scripts/generate-self-hosted-fonts.mjs
// Serves Roboto and Kristi from this site instead of fonts.googleapis.com and fonts.gstatic.com.
//
// Google's stylesheet was inlined by the build, so the cost was never the CSS request — it was the
// connection to fonts.gstatic.com that every page had to open before the woff2 files could start,
// sitting on the critical path next to the HTML. Self-hosting puts the fonts on the connection the
// page already has.
//
// Fidelity is the constraint. The @font-face rules are copied from Google's own response with only
// the URL rewritten, so descriptors, weights and unicode-range are unchanged. That matters: Google
// declares Roboto once per weight (400, 500, 700, 900) over a single variable file, and the site
// asks for weight 800 in dozens of places. Font matching resolves 800 to the 900 face today;
// collapsing the rules into one `font-weight: 400 900` range would render true 800 instead — a
// visible change to headings site-wide. Copying the rules verbatim avoids that.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = resolve(root, "apps/website/src/assets/fonts");
const indexHtml = resolve(root, "apps/website/src/index.html");
const QUERY = "family=Kristi&family=Roboto:wght@400;500;700;900&display=swap";
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/151.0.0.0 Safari/537.36";

// The subsets the site's text actually needs, found by scanning every prerendered page against
// each subset's unicode-range: the footer's telephone and envelope and the destinations arrow
// live in `symbols`, the Bulgarian licence name needs `cyrillic`, and everything else is latin.
// `math` also covers the arrow but is never used for it — overlapping ranges resolve to the face
// declared last, and Google declares `symbols` after `math`. Greek, Vietnamese and cyrillic-ext
// are unused. Order is preserved from Google's response for the same reason.
const KEEP = {
  Roboto: ["cyrillic", "symbols", "latin-ext", "latin"],
  Kristi: ["latin"],
};

const css = await (
  await fetch(`https://fonts.googleapis.com/css2?${QUERY}`, {
    headers: { "User-Agent": UA },
  })
).text();
const faces = [
  ...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g),
].map((m) => ({
  subset: m[1],
  rule: m[2],
  family: m[2].match(/font-family:\s*'([^']+)'/)[1],
  url: m[2].match(/url\(([^)]+)\)/)[1],
}));
const kept = faces.filter((f) => KEEP[f.family]?.includes(f.subset));

for (const [family, subsets] of Object.entries(KEEP)) {
  for (const subset of subsets) {
    if (!kept.some((f) => f.family === family && f.subset === subset)) {
      throw new Error(
        `Google no longer serves ${family} ${subset}; refusing to write a partial set.`,
      );
    }
  }
}

mkdirSync(fontsDir, { recursive: true });
const local = new Map();
for (const face of kept) {
  if (local.has(face.url)) continue;
  const version =
    face.url.split("/").find((part) => /^v\d+$/.test(part)) ?? "v0";
  const name = `${face.family.toLowerCase()}-${version}-${face.subset}.woff2`;
  const bytes = Buffer.from(
    await (
      await fetch(face.url, { headers: { "User-Agent": UA } })
    ).arrayBuffer(),
  );
  writeFileSync(resolve(fontsDir, name), bytes);
  local.set(face.url, {
    path: `/assets/fonts/${name}`,
    bytes: bytes.length,
    face,
  });
}

const rules = kept
  .map((f) =>
    f.rule
      .replace(f.url, local.get(f.url).path)
      .replace(/\s+/g, " ")
      .replace(/\s*([{};:,])\s*/g, "$1"),
  )
  .join("");
const latin = [...local.values()].find(
  (v) => v.face.family === "Roboto" && v.face.subset === "latin",
);

const block = [
  "<!-- self-hosted-fonts:start — generated by scripts/generate-self-hosted-fonts.mjs, do not edit -->",
  `    <link rel="preload" as="font" type="font/woff2" href="${latin.path}" crossorigin />`,
  `    <style>${rules}</style>`,
  "    <!-- self-hosted-fonts:end -->",
].join("\n");

let html = readFileSync(indexHtml, "utf8");
if (html.includes("self-hosted-fonts:start")) {
  html = html.replace(
    /<!-- self-hosted-fonts:start[\s\S]*?self-hosted-fonts:end -->/,
    block,
  );
} else {
  const googleLink =
    /<link\s+href="https:\/\/fonts\.googleapis\.com\/css2[^>]*>/;
  if (!googleLink.test(html)) {
    throw new Error(
      "index.html has neither the markers nor the Google Fonts link to replace.",
    );
  }
  html = html
    .replace(/[ \t]*<!--[^>]*fonts\.googleapis\.com[\s\S]*?-->\s*\n/, "")
    .replace(
      /[ \t]*<link rel="preconnect" href="https:\/\/fonts\.gstatic\.com"[^>]*>\s*\n/,
      "",
    )
    .replace(googleLink, block);
}
writeFileSync(indexHtml, html);

let total = 0;
for (const v of local.values()) {
  total += v.bytes;
  console.log(`${v.path.padEnd(42)} ${String(v.bytes).padStart(7)} bytes`);
}
console.log(
  `${kept.length} @font-face rules, ${local.size} files, ${total} bytes on disk.`,
);
console.log(
  "A page downloads only the subsets its own text needs — unicode-range is unchanged.",
);
